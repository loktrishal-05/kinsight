"""Reproducible scorecard (P4 exit) and generated limitations statement (P6-3). Run: python scripts/scorecard.py"""
import json
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from services.agents.copilot import answer  # noqa: E402
from services.agents.eval import run_eval  # noqa: E402
from services.agents.render import load_glossary  # noqa: E402
from services.analytics.capacity import compare  # noqa: E402
from services.consent.settings import settings  # noqa: E402

manifest = json.loads((ROOT / "data/demo/manifest.json").read_text())
ev = run_eval()
cap = compare(yaml.safe_load((ROOT / "configs/capacity.yaml").read_text()))
prompts = yaml.safe_load((ROOT / "tests/redteam/prompts.yaml").read_text(encoding="utf-8"))["prompts"]
gl = load_glossary()
ok = sum(answer(p["text"], p["lang"], ["x"], gl, []).refused == (p["expect"] == "refuse") for p in prompts)
priv = settings()

score = {
    "cohort": {"seed": manifest["seed"], "couples": manifest["counts"]["couples"],
               "consanguinity_share": manifest["achieved_consanguinity_share"],
               "mean_inbreeding_f": manifest["mean_inbreeding_f"], "all_rows_synthetic": manifest["is_synthetic"]},
    "explanations": {k: ev[k] for k in ("drafts", "numeric_fidelity", "block_conformity", "banned_phrases")},
    "red_team": {"prompts": len(prompts), "handled_correctly": ok},
    "privacy": {"min_cell": priv.min_cell, "epsilon_total": priv.epsilon_total, "epsilon_per_release": priv.epsilon_per_release},
    "time_to_care_simulation_illustrative": [{k: r[k] for k in ("policy", "median_days", "p95_days", "tier3_within_window")}
                                             for r in cap["runs"]],
    "comprehension": "not measured: the volunteer study (docs/study/protocol.md) has not been run",
}
(ROOT / "docs/scorecard.json").write_text(json.dumps(score, indent=1), encoding="utf-8")

lines = ["# Scorecard (generated by scripts/scorecard.py; reproducible from the committed seed)", ""]
lines += [f"- Cohort: {score['cohort']['couples']} synthetic couples, consanguinity share "
          f"{score['cohort']['consanguinity_share']:.3f}, mean inbreeding coefficient {score['cohort']['mean_inbreeding_f']:.4f}.",
          f"- Explanations: {ev['drafts']} drafts; numeric fidelity {ev['numeric_fidelity']:.0%}; block conformity "
          f"{ev['block_conformity']:.0%}; banned phrases {ev['banned_phrases']}.",
          f"- Copilot red-team set: {ok}/{len(prompts)} refused or answered safely (keyword rules tuned on this set).",
          f"- Privacy: cells under {priv.min_cell} suppressed; budget {priv.epsilon_total} (per release {priv.epsilon_per_release}).",
          "- Time to counsellor contact (illustrative simulation, not a forecast):"]
lines += [f"  - {r['policy']}: median {r['median_days']} d, p95 {r['p95_days']} d, tier 3 within window "
          f"{r['tier3_within_window']:.0%}" for r in cap["runs"]]
lines += ["- Comprehension: not measured. The volunteer study has not been run.", ""]
(ROOT / "docs/SCORECARD.md").write_text("\n".join(lines), encoding="utf-8")

lim = ["# Limitations statement (generated; see docs/limitations.md for detail)", "",
       "- All data are synthetic. No real genomes or personal data are stored, and every screen says results are fictional.",
       "- No clinical validation. The genetics formulas are standard textbook results not reviewed by a genetics professional here.",
       "- Arabic strings and templates are placeholders pending native-speaker review; none is marked approved.",
       f"- Scorecard figures above come from synthetic cohorts and code evaluators ({ev['drafts']} drafts, "
       f"{len(prompts)} red-team prompts); they are not evidence about real people.",
       "- Comprehension has not been measured; the planned small volunteer study on fictional cases has not been run and "
       "would be small and informal if run.",
       "- The capacity simulator is illustrative and shows its assumptions; it is not a forecast.",
       "- The partner check (PSI) is an unaudited demo; the FHIR export is a function with no route; voice depends on browser support.",
       ""]
(ROOT / "docs/limitations_generated.md").write_text("\n".join(lim), encoding="utf-8")
print("\n".join(lines))
