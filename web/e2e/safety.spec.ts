import { expect, test } from "@playwright/test";

test("check-in, both vault PINs, clinic triage and emergency access", async ({ page }) => {
  await page.goto("/signin");
  await page.getByTestId("demo-account").click();
  await page.getByTestId("signin-submit").click();
  await expect(page).toHaveURL(/\/home$/);
  await page.getByRole("button", { name: /Person A/ }).click();
  await page.goto("/checkin");
  await expect(page.getByRole("heading", { name: "Check-in and privacy tools" })).toBeVisible();
  const checkin = page.getByRole("region", { name: "Waiting-period check-in" });
  await checkin.getByLabel("Choose instrument").selectOption("low_literacy_dcs");
  for (let i = 1; i <= 10; i++) await checkin.getByLabel(new RegExp(`^Item ${i}([^0-9]|$)`)).selectOption("unsure");
  await checkin.getByRole("button", { name: "Submit check-in" }).click();
  await expect(checkin.getByRole("status")).toContainText("Score: 50");
  await expect(checkin.getByRole("status")).toContainText("A counsellor conversation is available");
  const vault = page.getByRole("region", { name: "Safe vault" });
  await vault.getByLabel("First PIN", { exact: true }).fill("1234");
  await vault.getByLabel("Second PIN", { exact: true }).fill("5678");
  await vault.getByRole("button", { name: "Save PINs" }).click();
  await expect(vault.getByText("PINs saved.", { exact: true })).toBeVisible();
  await vault.getByLabel("Enter a PIN").fill("1234");
  await vault.getByRole("button", { name: "Unlock", exact: true }).click();
  await expect(vault.getByText("Your summary will appear here.", { exact: true })).toBeVisible();
  await vault.getByRole("button", { name: "Lock", exact: true }).click();
  await expect(vault.getByText("Your summary will appear here.", { exact: true })).toHaveCount(0);
  await vault.getByLabel("Enter a PIN").fill("5678");
  await vault.getByRole("button", { name: "Unlock", exact: true }).click();
  await expect(vault.getByText("Standard premarital screen completed", { exact: true })).toBeVisible();
  await expect(vault.getByText("Your summary will appear here.", { exact: true })).toHaveCount(0);
  await page.goto("/home");
  await page.getByRole("button", { name: /^Counsellor/ }).click();
  await page.goto("/clinic");
  const triage = page.getByRole("region", { name: "Triage check" });
  await triage.getByLabel("Choose a preset").selectOption("pending");
  await triage.getByRole("button", { name: "Run triage" }).click();
  await expect(triage.getByRole("status")).toContainText("Tier: 3");
  await expect(triage.getByRole("status")).toContainText("25 in 100");
  await expect(triage.getByRole("status")).toContainText("Release is on hold pending confirmation.");
  const emergency = page.getByRole("region", { name: "Emergency access" });
  await emergency.getByLabel("First clinician ID").fill("demo-clinician-1");
  await emergency.getByLabel("Second clinician ID").fill("demo-clinician-2");
  await emergency.getByLabel("Reason").fill("Fictional emergency review");
  await emergency.getByRole("button", { name: "Request emergency access" }).click();
  await expect(emergency.getByRole("status")).toContainText("Alert raised");
  await expect(emergency.getByRole("status")).toContainText("Citizen notified");
});

test("roles outside care and clinic see restricted notices", async ({ page }) => {
  await page.goto("/signin");
  await page.getByTestId("demo-account").click();
  await page.getByTestId("signin-submit").click();
  await expect(page).toHaveURL(/\/home$/);
  await page.getByRole("button", { name: /Person A/ }).click();
  await page.goto("/clinic");
  await expect(page.getByText("This page is available to counsellors.")).toBeVisible();
  await expect(page.getByRole("heading", { name: "Emergency access" })).toHaveCount(0);
  await page.goto("/home");
  await page.getByRole("button", { name: /^Counsellor/ }).click();
  await page.goto("/checkin");
  await expect(page.getByText("This page is available in person views.")).toBeVisible();
});
